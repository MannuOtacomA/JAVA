package com.krakedev;

public class Fechas {
	
	private int dias;
	private int mes;
	private int ania;
	
	public int getDias() {
		return dias;
	}
	public void setDias(int dias) {
		this.dias = dias;
	}
	public int getMes() {
		return mes;
	}
	public void setMes(int mes) {
		this.mes = mes;
	}
	public int getAnia() {
		return ania;
	}
	public void setAnia(int ania) {
		this.ania = ania;
	}
	
	

}
